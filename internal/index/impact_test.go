func TestImpactSinceReportsBodyChangesDeletedSymbolsAndStructuralBlastRadius(t *testing.T) {
	fixture := newImpactFixture(t)
	writeImpactFile(t, fixture.service, "policy/policy.go", `package policy

type Authorizer interface { Decide() bool }
type Engine struct{}
func (e *Engine) Decide() bool { return true }
func Call(e *Engine) bool { return e.Decide() }
`)
	writeImpactFile(t, fixture.service, "policy/config.go", `package policy
type Config struct { Mode string; Strict bool }
`)
	writeImpactFile(t, fixture.service, "api/service.pb.go", `// Code generated by test. DO NOT EDIT.
package api
type ExampleServiceServer interface { Get(); Put() }
`)
	writeImpactFile(t, fixture.service, "policy/new.go", "package policy\nfunc Added() {}\n")
	if err := os.Remove(filepath.Join(fixture.service, "policy", "obsolete.go")); err != nil {
		t.Fatal(err)
	}

	idx, err := BuildIndex(fixture.cfg)
	if err != nil {
		t.Fatal(err)
	}
	holder := NewHolder(idx, fixture.cfg)
	report, err := holder.ImpactSince("service", fixture.base)
	if err != nil {
		t.Fatal(err)
	}
	for _, expected := range []struct {
		name   string
		change SymbolChangeKind
	}{
		{"Engine.Decide", SymbolModified},
		{"Config", SymbolModified},
		{"ExampleServiceServer", SymbolModified},
		{"Added", SymbolAdded},
		{"Removed", SymbolDeleted},
	} {
		if !impactHasChange(report.ChangedSymbols, expected.name, expected.change) {
			t.Errorf("missing %s %s in %#v", expected.name, expected.change, report.ChangedSymbols)
		}
	}
	if !impactHasSymbol(report.AffectedSymbols, "Call") || !impactHasSymbol(report.AffectedSymbols, "Use") {
		t.Errorf("callers absent from affected symbols: %#v", report.AffectedSymbols)
	}
	if !impactHasSymbol(report.Interfaces, "Authorizer") {
		t.Errorf("implicit interface absent: %#v", report.Interfaces)
	}
	if !impactHasSymbol(report.ConfigStructs, "Config") {
		t.Errorf("config struct absent: %#v", report.ConfigStructs)
	}
	if !impactHasSymbol(report.Services, "ExampleServiceServer") {
		t.Errorf("service absent: %#v", report.Services)
	}
	if !impactHasSymbol(report.CandidateTests, "TestDefaultDeny") {
		t.Errorf("candidate test absent: %#v", report.CandidateTests)
	}
	if !includesImpactString(report.AffectedRepositories, "consumer") {
		t.Errorf("cross-repository impact absent: %v", report.AffectedRepositories)
	}
	if report.Snapshot.Repository != "service" || report.Snapshot.BaseCommit != fixture.base ||
		report.Snapshot.HeadCommit == "" || report.Snapshot.TrackedDiffDigest == "" ||
		report.Snapshot.UntrackedManifestDigest == "" || report.Snapshot.WorktreeDigest == "" ||
		report.Snapshot.Generation != 1 || report.Snapshot.ToolchainIdentity == "" || report.ImpactDigest == "" {
		t.Fatalf("snapshot or digest incomplete: %#v", report)
	}
	if report.ImpactDigest != ImpactDigest(report) {
		t.Fatalf("impact digest is not reproducible: %#v", report)
	}
}

func TestImpactSinceRejectsSourceChangedAfterPublishedIndex(t *testing.T) {
	fixture := newImpactFixture(t)
	idx, err := BuildIndex(fixture.cfg)
	if err != nil {
		t.Fatal(err)
	}
	holder := NewHolder(idx, fixture.cfg)
	writeImpactFile(t, fixture.service, "policy/policy.go", `package policy
type Authorizer interface { Decide() bool }
type Engine struct{}
func (e *Engine) Decide() bool { return true }
func Call(e *Engine) bool { return e.Decide() }
`)
	if _, err := holder.ImpactSince("service", fixture.base); err == nil || !strings.Contains(err.Error(), "reindex") {
		t.Fatalf("stale index error = %v", err)
	}
}

